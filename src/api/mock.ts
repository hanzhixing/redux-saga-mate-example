type TodoForeignKey = {
    creator: User | null;
    assignee: User | null;
};

export const getManyTodo = ($offset: number = 1, $limit: number = 5) => {
    const findUserById = (v: number): User | undefined => find<User>(propEq(v, 'id'), user);

    return compose(
        map((o: Todo): Denormalize<Todo, TodoForeignKey> => ({
            ...o,
            creator: findUserById(o.creator) || null,
            assignee: findUserById(o.assignee) || null,
        })),
        slice($offset, $offset + $limit)<Todo>,
        reverse<Todo>,
        sortBy(prop('id')),
    )(todo);
};
